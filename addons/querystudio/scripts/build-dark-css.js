// ---- reading the CSS ----

function stylesOfView(file) {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
  return [...src.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).filter((css) => !/^\s*@import/.test(css)).join('\n');
}
function cssOfWidget(file) {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const m = /var CSS = ([\s\S]*?);\n/.exec(src);
  if (!m) throw new Error('No "var CSS = …;" in ' + file);
  return new Function('return ' + m[1])();   // eslint-disable-line no-new-func
}

// Rules as { selectors, decls, media } (one level of @media).
function parseCss(css, media) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const rules = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (/^@media/.test(head)) rules.push(...parseCss(body, head));
    else if (head && !/^@/.test(head)) rules.push({ selectors: head.split(',').map((s) => s.trim()).filter(Boolean), body, media });
    i = j;
  }
  return rules;
}

function darkDecls(body) {
  const out = [];
  body.split(';').forEach((d) => {
    const k = d.indexOf(':');
    if (k < 0) return;
    const prop = d.slice(0, k).trim().toLowerCase();
    const value = d.slice(k + 1).trim();
    if (!COLOR_RE.test(value)) return;
    COLOR_RE.lastIndex = 0;
    const map = TEXT_PROPS.test(prop) ? TEXT : SURFACE;
    let changed = false;
    const next = value.replace(COLOR_RE, (c) => {
      const to = map[c.toLowerCase()];
      if (!to) return c;
      changed = true;
      return to;
    });
    if (changed) out.push(`${prop}: ${next}`);
  });
  return out;
}

const scope = (sel) => (/^(html|:root)\b/.test(sel) ? sel.replace(/^(html|:root)/, 'html.qs-dark') : 'html.qs-dark ' + sel);

let css = BASE;
const sources = VIEWS.map((f) => [f, stylesOfView(f)]).concat(WIDGETS.map((f) => [f, cssOfWidget(f)]));
let count = 0;
sources.forEach(([file, text]) => {
  const lines = [];
  parseCss(text).forEach((r) => {
    const decls = darkDecls(r.body);
    if (!decls.length) return;
    const rule = `${r.selectors.map(scope).join(', ')} { ${decls.join('; ')}; }`;
    lines.push(r.media ? `${r.media} { ${rule} }` : rule);
  });
  count += lines.length;
  css += `\n/* ${file} */\n` + lines.join('\n') + '\n';
});
fs.writeFileSync(OUT, css);
console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${count} rules from ${sources.length} files`);
